from plume_core.contacts_strings import CONTACTS  # noqa: E402

for _lang, _texts in CONTACTS.items():
    TEXT[_lang].update({k: v for k, v in _texts.items() if k not in TEXT[_lang]})


def language() -> str:
    lang = QLocale.system().name()[:2]
    return lang if lang in TEXT else "fr"


def strings() -> dict:
    return TEXT[language()]
