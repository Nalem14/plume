def language() -> str:
    lang = QLocale.system().name()[:2]
    return lang if lang in TEXT else "fr"


def strings() -> dict:
    """The texts; the lock speaks of the Windows or Mac password in Plume on those systems."""
    import system  # noqa: PLC0415
    t = dict(TEXT[language()])
    if system.WINDOWS:
        t["locked_lead"], t["session_password"] = t["locked_lead_windows"], t["session_password_windows"]
    elif system.MACOS:
        t["locked_lead"] = t["locked_lead_macos"]
    return t
